return function(test)
  test.Loader.LoadAddon(test.tocPath, "WeakAuras", {})
  test.Environment.Advance(1)
  WeakAuras.InitEnergyTick()
  local function Energy() test.Frames.Fire("UNIT_POWER_FREQUENT", "player", "ENERGY") end
  local function Cast() test.Frames.Fire("UNIT_SPELLCAST_SUCCEEDED", "player", "Cast-0", 1752, 1) end
  local function Next(expected, step)
    local duration, expirationTime = WeakAuras.GetEnergyTickInfo()
    assert(duration == 2, step .. ": duration " .. tostring(duration))
    assert(math.abs(expirationTime - GetTime() - expected) < 0.01,
      step .. ": next tick in " .. tostring(expirationTime - GetTime()) .. ", expected " .. expected)
  end

  assert(WeakAuras.GetEnergyTickInfo() == 0, "tick known before any energy event")
  Energy()
  Next(2, "first tick")
  test.Environment.Advance(0.7)
  Cast()
  Energy()
  Next(1.3, "spend after cast")
  test.Environment.Advance(0.5)
  Energy()
  Cast()
  Next(0.8, "spend before cast")
  test.Environment.Advance(0.8)
  Energy()
  Next(2, "regular tick")
  test.Environment.Advance(0.9)
  Energy()
  Next(1.1, "single gain out of phase")
  test.Environment.Advance(2)
  Energy()
  Next(2, "relock after two gains two seconds apart")
  test.Environment.Advance(3)
  Next(1, "cycle continues at full energy")
end
